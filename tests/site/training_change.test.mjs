import assert from 'node:assert/strict';
import fs from 'node:fs';
import {checkpointChart, evaluationTable, probeHeatmap, trainingChangeHTML} from '../../docs/js/training-change.js';
const model = {stages: [{stage:'pretrain'}, {stage:'sft'}, {stage:'dpo'}, {stage:'rlvr'}]};
const evaluations = {benchmarks:[{name:'Math <test>', category:'Math', scores:{sft:0,dpo:10,rlvr:8}}], note:'Publisher reported', source:'https://example.com'};
const html = evaluationTable(model.stages, evaluations);
assert.ok(html.includes('Not reported'));
assert.ok(html.includes('0.0'));
assert.ok(html.includes('+10.0 pp'));
assert.ok(html.includes('-2.0 pp'));
assert.ok(html.includes('Math &lt;test&gt;'));
assert.ok(!html.includes('NaN'));
const missing = trainingChangeHTML(model, null, null, {stage:'sft',mode:'weights'});
assert.ok(missing.includes('0 of 4 phases with weight measurements'));
assert.ok(missing.includes('have not been compared'));
assert.ok(!missing.includes('≥ 0'));
const raw = JSON.parse(fs.readFileSync(new URL('../../results/pythia-70m-deduped.changes.json', import.meta.url)));
const graph = checkpointChart(raw.stages[0].checkpoints);
assert.ok(graph.includes('equally spaced'));
assert.ok(graph.includes('Step 143,000'));
assert.ok(!graph.includes('NaN'));
const measured = trainingChangeHTML({stages:[{stage:'pretrain'}]}, raw, null, {stage:'pretrain',mode:'weights'});
assert.ok(measured.includes('lower bound from 4 checkpoints'));
assert.ok(measured.includes('Transformer block 1'));
assert.ok(measured.includes(raw.stages[0].checkpoints[0].resolved_revision));
const probes = probeHeatmap(model.stages, raw);
assert.ok(probes.includes('Not measured'));
assert.ok(probes.includes('Jensen–Shannon'));
const flat = checkpointChart([{net_rms:0,observed_path_rms:0,label:'Start'}, {net_rms:0,observed_path_rms:0,label:'End'}]);
assert.ok(!flat.includes('NaN'));
assert.ok(!flat.includes('Infinity'));
const zero = structuredClone(raw);
zero.stages[0].behavior.topics[0].js_bits = 0;
assert.ok(probeHeatmap([{stage:'pretrain'}], zero).includes('>0</td>'));
console.log('ok training change: missing vs zero, signed changes, provenance, measured charts, and escaping');
